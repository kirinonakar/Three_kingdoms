"""Build the bundled PCM bank from CC0 Still North Media blade recordings.

Usage: python tools/build_sword_samples.py <directory with original WAV files>
Requires ffmpeg and numpy. Original files and license: AUDIO_CREDITS.md.
The resulting script needs no fetch, codecs, or async decoding on file://.
"""
import base64
import hashlib
import json
from pathlib import Path
import subprocess
import sys

import numpy as np

RATE = 44100
ROOT = Path(__file__).resolve().parents[1]
TAKES = [
    ("Sabre Katana Blade on Blade.wav", 0.46, 0.46),
    ("Sabre Katana Blade on Blade.wav", 2.65, 0.50),
    ("Norse Sword Katana Blade on Blade.wav", 13.86, 0.52),
    ("Sabre Norse Sword Blade on Blade.wav", 12.46, 0.48),
]


def main():
    source_dir = Path(sys.argv[1])
    bank, provenance = [], []
    for name, impact, duration in TAKES:
        source = source_dir / name
        raw = subprocess.check_output([
            "ffmpeg", "-v", "error", "-ss", str(impact - 0.08), "-i", str(source),
            "-t", str(duration + 0.15), "-ac", "1", "-ar", str(RATE),
            "-af", "highpass=f=220,lowpass=f=9500,"
                   "equalizer=f=750:t=o:w=1:g=-4,"
                   "acompressor=threshold=0.12:ratio=3:attack=0.5:release=40",
            "-f", "f32le", "-"
        ])
        data = np.frombuffer(raw, dtype="<f4").copy()
        # Remove pre-hit silence while retaining a short natural attack.
        head = data[:int(RATE * 0.13)]
        onset = np.flatnonzero(np.abs(head) > np.max(np.abs(head)) * 0.06)[0]
        start = max(0, int(onset) - int(RATE * 0.002))
        data = data[start:start + int(duration * RATE)]
        data -= np.mean(data)
        fade_in, fade_out = int(RATE * 0.0007), int(RATE * 0.045)
        data[:fade_in] *= np.linspace(0, 1, fade_in)
        data[-fade_out:] *= np.linspace(1, 0, fade_out)
        # 드문 단일 피크에 전체 음량이 끌려 내려가지 않게 부드럽게 제한한다.
        data = np.tanh(data * (1.5 / np.max(np.abs(data))))
        data *= 0.8 / np.max(np.abs(data))
        pcm = np.round(np.clip(data, -1, 1) * 32767).astype("<i2").tobytes()
        bank.append(base64.b64encode(pcm).decode("ascii"))
        provenance.append({
            "file": name, "impact_seconds": impact,
            "duration": duration,
            "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "pcm_sha256": hashlib.sha256(pcm).hexdigest(),
        })
        print(f"{name} @ {impact}s: {len(data) / RATE:.2f}s, "
              f"peak {np.max(np.abs(data)):.3f}, RMS {np.sqrt(np.mean(data ** 2)):.3f}")
    header = ("// Generated by tools/build_sword_samples.py. Do not edit PCM by hand.\n"
              "// CC0: Ben Jaszczak & Brian Nelson / Still North Media. See AUDIO_CREDITS.md.\n"
              "// Mono signed 16-bit little-endian PCM, base64; no network/decoder needed.\n")
    content = header + "const SwordSamples = " + json.dumps({
        "sampleRate": RATE, "pcm16": bank
    }, separators=(",", ":")) + ";\n"
    (ROOT / "js" / "sword-samples.js").write_text(content, encoding="utf-8")
    (ROOT / "tools" / "sword_samples_manifest.json").write_text(
        json.dumps(provenance, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
