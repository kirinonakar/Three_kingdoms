function scenarioOfficer(o,s,cities) {
  const copy=o.slice(), dead=(s.deaths||'').split(' ').includes(o[0]);
  if(dead) return {def:copy,retired:true};
  // 로스터를 직접 지정한 시나리오: 로스터에 없는 무장은 재야로 시작한다.
  const drafted=s.rosters && Object.keys(s.rosters).find(fid=>s.rosters[fid].includes(o[0]));
  if(s.rosters) {
    copy[1]=drafted || 'free';
    if(copy[1]!=='free') {
      const home=cities.find(c=>c[0]===copy[2] && c[4]===copy[1]) || cities.find(c=>c[4]===copy[1]);
      if(home) copy[2]=home[0];
    }
    return {def:copy,retired:false};
  }
  const owners=new Set(cities.map(c=>c[4]));
  const assigned=s.assignments && s.assignments[o[0]];
  if((o[8]||194)<=s.year && s.owners) {
    copy[1]=assigned || (s.transfers && s.transfers[o[1]]) || o[1];
    if(copy[1]==='free' && o[9] && owners.has(o[9])) copy[1]=o[9];
    if(copy[1]!=='free' && !owners.has(copy[1])) copy[1]='free';
    if(copy[1]!=='free') {
      const home=cities.find(c=>c[0]===copy[2] && c[4]===copy[1]) || cities.find(c=>c[4]===copy[1]);
      if(home) copy[2]=home[0];
    }
  }
  return {def:copy,retired:false};
}
