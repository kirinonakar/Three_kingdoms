/* ── 지도 투영 : 실제 경위도 → 캔버스 좌표 ────────────────────────
   등장방형(equirectangular) 투영. 기준 위도 30°에서 경도 1° ≈ 96.4km,
   위도 1° ≈ 111km 로 x·y 축척을 맞춰 실제 지형 비율을 유지한다. */
const MAP_VIEW = (function () {
  const lon0 = 96, lon1 = 129, lat0 = 21, lat1 = 43.5, W = 1200, H = 1000;
  const s = Math.min(W / ((lon1 - lon0) * 96.4), H / ((lat1 - lat0) * 111));
  const kx = 96.4 * s, ky = 111 * s;
  return {
    lon0, lon1, lat0, lat1, W, H, kx, ky,
    ox: (W - (lon1 - lon0) * kx) / 2,
    oy: (H - (lat1 - lat0) * ky) / 2
  };
})();
function projMap(lon, lat) {
  return [MAP_VIEW.ox + (lon - MAP_VIEW.lon0) * MAP_VIEW.kx,
          MAP_VIEW.oy + (MAP_VIEW.lat1 - lat) * MAP_VIEW.ky];
}
/* 실제 경위도(선택적 미세 보정 dLon, dLat) → [x, y] */
function LL(lon, lat, dLon, dLat) {
  const p = projMap(lon + (dLon || 0), lat + (dLat || 0));
  return [Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10];
}

